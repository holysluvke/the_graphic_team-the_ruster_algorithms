def placeholder(master, text):
    frame = ttk.Frame(master)
    ttk.Label(frame, text=text, font=("Segoe UI", 14)).pack(expand=True, pady=40)
    return frame


def main():
    root = tk.Tk()
    root.title("Растровые алгоритмы")

    tabs = ttk.Notebook(root)
    tabs.pack(fill=tk.BOTH, expand=True)

    tabs.add(Task1Frame(tabs), text="Задание 1: заливка и граница")
    tabs.add(Task2Frame(tabs), text="Задание 2: отрезки")

    # TODO: заменить заглушку на вкладку задания 3
    tabs.add(
        placeholder(tabs, "Задание 3 - вставить сюда"), text="Задание 3: треугольник"
    )

    root.mainloop()


if __name__ == "__main__":
    main()
